//! Window commands, split by responsibility (geometry, persistence, ball,
//! surface). Everything stays re-exported from `commands::window` so command
//! paths and `generate_handler!` registration in `lib.rs` are unchanged.

mod ball;
mod geometry;
mod position;
mod surface;

pub use ball::{collapse_to_ball, expand_from_ball};
pub use position::{
    keep_window_visible, restore_main_window, save_ball_position, save_window_position,
};
#[cfg(debug_assertions)]
pub use surface::open_debug;
pub use surface::{
    active_window_label, open_devtools, open_panel, present_foreground, set_active_window,
    start_visibility_watch, ActiveWindow,
};
// Kept for the module's public surface; `start_visibility_watch` is the only
// caller and lives in the same module.
#[allow(unused_imports)]
pub use surface::keep_windows_visible;

// `generate_handler!` looks for `__cmd__*` next to the path given in `lib.rs`.
// Each submodule forwards the wrapper macro generated by `#[tauri::command]`.
#[doc(hidden)]
pub use ball::{__cmd__collapse_to_ball, __cmd__expand_from_ball};
#[doc(hidden)]
pub use position::{
    __cmd__keep_window_visible, __cmd__save_ball_position, __cmd__save_window_position,
};
#[cfg(debug_assertions)]
#[doc(hidden)]
pub use surface::__cmd__open_debug;
#[doc(hidden)]
pub use surface::{__cmd__open_devtools, __cmd__open_panel, __cmd__set_active_window};
